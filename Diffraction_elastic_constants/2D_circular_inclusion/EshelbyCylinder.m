function S = EshelbyCylinder(nu)

    S = zeros(3,3,3,3);
    S(1,1,1,1) = 1/(2*(1-nu)) * (3/4 + (1-2*nu)*1/2);
    S(2,2,2,2) = 1/(2*(1-nu)) * (3/4 + (1-2*nu)*1/2);
    S(3,3,3,3) = 0;
    S(1,1,2,2) = 1/(2*(1-nu)) * (1/4 - (1-2*nu)*1/2);
    S(1,1,3,3) = 1/(2*(1-nu)) * nu;
    S(2,2,3,3) = 1/(2*(1-nu)) * nu;
    S(2,2,1,1) = 1/(2*(1-nu)) * (1/4 - (1-2*nu)*1/2);
    S(3,3,1,1) = 0;
    S(3,3,2,2) = 0;
    
    S(1,2,1,2) = 1/(2*(1-nu)) * (1/4 + (1-2*nu)*1/2);
    S(2,1,1,2) = S(1,2,1,2);
    S(1,2,2,1) = S(1,2,1,2);
    S(2,1,2,1) = S(1,2,1,2);
    
    S(2,3,2,3) = 1/4;
    S(3,2,2,3) = S(2,3,2,3);
    S(2,3,3,2) = S(2,3,2,3);
    S(3,2,3,2) = S(2,3,2,3);
    
    S(3,1,3,1) = 1/4;
    S(1,3,3,1) = S(3,1,3,1);
    S(3,1,1,3) = S(3,1,3,1);
    S(1,3,1,3) = S(3,1,3,1);


end